import { expect, test } from '@playwright/test'
import { activatePairsWithMouse, loadBoard, pairsFor } from './fixtures.ts'

test('finishes every supported board with its exact pair and move count', async ({ page }) => {
  await page.goto('/')
  await loadBoard(page, 'np1-4-1')
  for (const side of [4, 6, 8, 10, 12, 14, 16]) {
    if (side !== 4) await page.getByLabel('Grid size').selectOption(String(side))
    const code = await page.getByLabel('Board code').inputValue()
    const pairs = pairsFor(code)
    const total = side * side / 2
    await expect(page.locator('.card')).toHaveCount(side * side)
    await activatePairsWithMouse(page, pairs)
    const status = page.getByRole('region', { name: 'Game status' })
    await expect(status).toContainText(`Moves: ${total}`)
    await expect(status).toContainText(`Pairs: ${total}/${total}`)
    await expect(page.locator('.win-banner')).toContainText(`All pairs found in ${total} moves and`)
  }
})

test('repeats a first card without a move and plays the 800ms mismatch', async ({ page }) => {
  await page.clock.pauseAt(new Date('2025-01-01T00:00:00Z'))
  await page.goto('/')
  await loadBoard(page, 'np1-4-1')
  const cards = page.locator('.card')
  await expect(page.locator('.card svg')).toHaveCount(0)
  const hiddenMarkup = await cards.evaluateAll((buttons) => buttons.map((button) => button.outerHTML).join(' '))
  expect(hiddenMarkup).not.toContain('<svg')
  expect(await cards.nth(0).getAttribute('aria-label')).toBe('Row 1, column 1, closed')
  await cards.nth(0).click()
  await cards.nth(0).click()
  await expect(page.getByText('Moves: 0')).toBeVisible()
  await cards.nth(1).click()
  await expect(page.locator('.live-announcement')).toHaveText('No match. Cards close after a short pause.')
  await expect(page.getByText('Moves: 1')).toBeVisible()
  await page.clock.runFor(799)
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /revealed$/)
  await page.clock.runFor(1)
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /closed$/)
  await expect(cards.nth(1)).toHaveAttribute('aria-label', /closed$/)
  await expect(page.locator('.live-announcement')).toHaveText('No match. Cards close after a short pause.')

  const originalNotice = await page.locator('.live-announcement span').elementHandle()
  await cards.nth(3).hover()
  await cards.nth(5).dispatchEvent('pointerdown', { bubbles: true, button: 0, pointerId: 4, pointerType: 'mouse' })
  await cards.nth(5).dispatchEvent('pointercancel', { bubbles: true, pointerId: 4, pointerType: 'mouse' })
  await cards.nth(5).click({ button: 'right' })
  await expect(cards.nth(5)).toHaveAttribute('aria-label', /closed$/)
  await expect(page.getByText('Moves: 1')).toBeVisible()
  await cards.nth(2).click()
  await cards.nth(10).click()
  const repeated = page.locator('.live-announcement span')
  await expect(repeated).toHaveText('No match. Cards close after a short pause.')
  if (originalNotice === null) throw new Error('A live announcement must exist')
  await expect.poll(() => originalNotice.evaluate((element) => element.isConnected)).toBe(false)
  await cards.nth(2).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('.live-announcement')).toHaveText('No match. Cards close after a short pause.')
  await page.clock.runFor(800)
  await expect(repeated).toHaveText('No match. Cards close after a short pause.')
})

test('invalid board codes and snapshots keep the game and drafts', async ({ page }) => {
  await page.goto('/')
  await loadBoard(page, 'np1-4-1')
  await page.locator('.card').nth(0).click()
  const savedBeforeError = await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))
  const codeInput = page.getByLabel('Board code')
  await codeInput.fill('np1-4-01')
  await page.getByRole('button', { name: 'Load board' }).click()
  await expect(page.locator('.reproduction-status')).toHaveText('Invalid board code.')
  await expect(page.locator('.live-announcement')).toHaveText('Invalid board code.')
  await expect(page.getByRole('button', { name: 'Load board' })).toBeFocused()
  await expect(codeInput).toHaveValue('np1-4-01')
  await expect(page.getByText('Moves: 0')).toBeVisible()
  await expect(page.locator('.card').nth(0)).toHaveAttribute('aria-label', /revealed$/)
  expect(await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))).toBe(savedBeforeError)
  await page.getByLabel('Snapshot JSON').fill('{')
  await page.getByRole('button', { name: 'Load snapshot' }).click()
  await expect(page.locator('.reproduction-status')).toHaveText('Invalid snapshot.')
  await expect(page.getByRole('button', { name: 'Load snapshot' })).toBeFocused()
  await expect(page.getByLabel('Snapshot JSON')).toHaveValue('{')
  await expect(page.locator('.card').nth(0)).toHaveAttribute('aria-label', /revealed$/)
})
