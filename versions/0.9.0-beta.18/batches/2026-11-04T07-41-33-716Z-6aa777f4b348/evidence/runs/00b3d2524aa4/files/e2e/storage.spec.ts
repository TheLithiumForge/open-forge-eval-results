import { expect, test } from '@playwright/test'
import { activatePairsWithMouse, finishedSnapshot, loadBoard, openReproduction, pairsFor, snapshotFromTextarea, unfinishedSnapshot } from './fixtures.ts'

test('remembers size, starts fresh deals, and preserves unrelated storage', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('another-tool', 'keep this value'))
  await page.goto('/')
  await openReproduction(page)
  await page.getByLabel('Grid size').selectOption('16')
  const firstCode = await page.getByLabel('Board code').inputValue()
  await expect(page.locator('.card')).toHaveCount(256)
  await expect(page.getByText('Best: none')).toBeVisible()
  await page.locator('.card').nth(0).click()
  await expect(page.locator('.card').nth(0)).toHaveAttribute('aria-label', /revealed$/)
  await page.reload()
  const refreshedCode = await page.getByLabel('Board code').inputValue()
  expect(refreshedCode).not.toBe(firstCode)
  await expect(page.locator('.card').nth(0)).toHaveAttribute('aria-label', /closed$/)
  await expect(page.getByText('Moves: 0')).toBeVisible()
  await page.getByRole('button', { name: 'New Game' }).click()
  const secondCode = await page.getByLabel('Board code').inputValue()
  expect(secondCode).not.toBe(refreshedCode)
  await expect(page.getByText('Moves: 0')).toBeVisible()
  const saved = await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))
  expect(saved).toContain('"size":16')
  expect(await page.evaluate(() => localStorage.getItem('another-tool'))).toBe('keep this value')

  await page.reload()
  await expect(page.getByLabel('Grid size')).toHaveValue('16')
  await expect(page.locator('.card')).toHaveCount(256)
  await expect(page.getByText('Moves: 0')).toBeVisible()
  expect(await page.getByLabel('Board code').inputValue()).not.toBe(secondCode)
})

test('keeps the best only when a completed result is strictly better', async ({ page }) => {
  await page.clock.pauseAt(new Date('2025-01-01T00:00:00Z'))
  await page.goto('/')
  const code = 'np1-4-1'
  await loadBoard(page, code)
  const pairs = pairsFor(code)
  const cards = page.locator('.card')
  await cards.nth(0).click()
  await cards.nth(1).click()
  await page.clock.runFor(800)
  await activatePairsWithMouse(page, pairs)
  const status = page.getByRole('region', { name: 'Game status' })
  await expect(status).toContainText('Moves: 9')
  await expect(status).toContainText('Best: 9')

  const savedBeforeImport = await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))
  await snapshotFromTextarea(page, finishedSnapshot(code, 8, 1500))
  await expect(status).toContainText('Moves: 8')
  await expect(status).toContainText('Best: 9')
  await expect(page.locator('.win-banner')).not.toHaveClass(/win-banner--pulse/)
  expect(await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))).toBe(savedBeforeImport)

  await loadBoard(page, code)
  await activatePairsWithMouse(page, pairs)
  await expect(status).toContainText('Best: 8')
  const savedAtEight = await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))
  await loadBoard(page, code)
  await activatePairsWithMouse(page, pairs)
  expect(await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))).toBe(savedAtEight)
  await loadBoard(page, code)
  await cards.nth(0).click()
  await cards.nth(1).click()
  await page.clock.runFor(800)
  await activatePairsWithMouse(page, pairs)
  await expect(status).toContainText('Moves: 9')
  await expect(status).toContainText('Best: 8')
  await page.reload()
  await expect(page.getByText('Best: 8')).toBeVisible()
})

test('ignores malformed preferences and remains playable when storage throws', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('neon-pairs.preferences.v1', '{"version":1,"size":5,"bests":{"4":1000000}}'))
  await page.goto('/')
  await expect(page.getByLabel('Grid size')).toHaveValue('4')
  await expect(page.getByText('Best: none')).toBeVisible()
  await expect(page.locator('.card')).toHaveCount(16)
  await page.locator('.card').nth(0).click()
  await expect(page.getByText('Moves: 0')).toBeVisible()

  const blocked = await page.context().newPage()
  await blocked.addInitScript(() => Object.defineProperty(window, 'localStorage', { configurable: true, get: () => { throw new Error('storage blocked') } }))
  await blocked.goto('/')
  await expect(blocked.getByLabel('Grid size')).toHaveValue('4')
  await blocked.getByLabel('Grid size').selectOption('6')
  await expect(blocked.locator('.card')).toHaveCount(36)
  await blocked.locator('.card').nth(0).click()
  await expect(blocked.getByText('Moves: 0')).toBeVisible()
  await blocked.close()
})

test('records a local best after resuming and completing an unfinished import', async ({ page }) => {
  await page.goto('/')
  const code = 'np1-4-1'
  const pairs = pairsFor(code)
  const finalPair = pairs[pairs.length - 1]
  if (finalPair === undefined) throw new Error('Final pair must exist')
  await snapshotFromTextarea(page, unfinishedSnapshot(code))
  await expect(page.getByRole('button', { name: 'Resume' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Game status' })).toContainText('Pairs: 7/8')
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(page.locator('.card').nth(0)).toBeFocused()
  await page.locator('.card').nth(finalPair[1]).click()
  await expect(page.locator('.live-announcement')).toContainText(/Pair found\. All pairs found in 8 moves and/)
  await expect(page.getByRole('region', { name: 'Game status' })).toContainText('Best: 8')
  expect(await page.evaluate(() => localStorage.getItem('neon-pairs.preferences.v1'))).toContain('"4":8')
})
