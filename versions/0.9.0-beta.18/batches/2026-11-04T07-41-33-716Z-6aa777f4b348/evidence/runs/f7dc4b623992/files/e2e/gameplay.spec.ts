import { expect, test } from '@playwright/test'
import { boardPairs, installTestClock, loadBoard, openReproduction, pauseTestClock } from './helpers.ts'

for (const size of [4, 6, 8, 10, 12, 14, 16]) {
  test(`${size}x${size} board can be completed with the documented positions`, async ({ page }) => {
    test.setTimeout(size === 16 ? 240_000 : 60_000)
    await page.goto('/')
    const code = `np1-${size}-1`
    await loadBoard(page, code)
    const cards = page.getByRole('group', { name: `${size} by ${size} card board` }).getByRole('button')
    for (const [first, second] of boardPairs(code)) {
      await cards.nth(first).click()
      await cards.nth(second).click()
    }
    const pairs = (size * size) / 2
    await expect(page.getByText(`Pairs: ${pairs}/${pairs}`, { exact: true })).toBeVisible()
    await expect(page.getByText(`Best: ${pairs}`, { exact: true })).toBeVisible()
    await expect(page.getByText('Every pair found!', { exact: true })).toBeVisible()
  })
}

test('repeated selection is free; a mismatch costs one move and closes after 800ms', async ({ page }) => {
  await installTestClock(page)
  await page.goto('/')
  await pauseTestClock(page)
  await loadBoard(page)
  const cards = page.getByRole('group', { name: '4 by 4 card board' }).getByRole('button')
  await cards.nth(0).click()
  await cards.nth(0).click()
  await expect(page.getByText('Moves: 0', { exact: true })).toBeVisible()
  await cards.nth(1).click()
  await expect(page.getByText('Moves: 1', { exact: true })).toBeVisible()
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /revealed$/)
  await expect(cards.nth(1)).toHaveAttribute('aria-label', /revealed$/)
  await cards.nth(2).click()
  await expect(page.getByText('Moves: 1', { exact: true })).toBeVisible()
  await page.clock.runFor(799)
  await cards.nth(2).click()
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /revealed$/)
  await page.clock.runFor(1)
  await cards.nth(2).click()
  await expect(cards.nth(0)).toHaveAttribute('aria-label', 'Row 1, column 1, closed')
  await expect(cards.nth(1)).toHaveAttribute('aria-label', 'Row 1, column 2, closed')
  await expect(page.getByText('Moves: 1', { exact: true })).toBeVisible()
})

test('restart and New Game clear a mismatch without allowing its old timer to act', async ({ page }) => {
  await installTestClock(page)
  await page.goto('/')
  await pauseTestClock(page)
  await loadBoard(page)
  const cards = page.getByRole('group', { name: '4 by 4 card board' }).getByRole('button')
  await cards.nth(0).click()
  await cards.nth(1).click()
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /revealed$/)
  await page.getByRole('button', { name: 'Restart' }).click()
  await expect(page.getByText('Moves: 0', { exact: true })).toBeVisible()
  await cards.nth(2).click()
  await page.clock.runFor(1_000)
  await expect(cards.nth(2)).toHaveAttribute('aria-label', /revealed$/)
  await page.getByRole('button', { name: 'New Game' }).click()
  await cards.nth(0).click()
  await cards.nth(1).click()
  await page.getByRole('button', { name: 'New Game' }).click()
  await expect(page.getByText('Moves: 0', { exact: true })).toBeVisible()
  await cards.nth(3).click()
  await page.clock.runFor(1_000)
  await expect(cards.nth(3)).toHaveAttribute('aria-label', /revealed$/)
})

test('invalid board and snapshot loads retain the active game and each entered draft', async ({ page }) => {
  await page.goto('/')
  await loadBoard(page)
  const cards = page.getByRole('group', { name: '4 by 4 card board' }).getByRole('button')
  await cards.nth(0).click()
  await openReproduction(page)
  const code = page.getByLabel('Board code')
  await code.fill('np1-3-1')
  await page.getByRole('button', { name: 'Load board' }).click()
  await expect(page.locator('.reproduction-status')).toHaveText('Invalid board code.')
  await expect(code).toHaveValue('np1-3-1')
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /revealed$/)
  const snapshot = page.getByLabel('Snapshot JSON')
  await snapshot.fill('{')
  await page.getByRole('button', { name: 'Load snapshot' }).click()
  await expect(page.locator('.reproduction-status')).toHaveText('Invalid snapshot.')
  await expect(snapshot).toHaveValue('{')
  await expect(cards.nth(0)).toHaveAttribute('aria-label', /revealed$/)
})

test('the deal and reproduction controls keep their labels, limits and focus', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByLabel('Grid size')).toHaveValue('4')
  await expect(page.getByLabel('Grid size').locator('option')).toHaveText(['4x4', '6x6', '8x8', '10x10', '12x12', '14x14', '16x16'])
  await expect(page.getByText('Reproduce a game', { exact: true })).toBeVisible()
  await expect(page.getByText('Reproduce a game', { exact: true }).locator('..')).not.toHaveAttribute('open', '')
  await openReproduction(page)
  const code = page.getByLabel('Board code')
  const snapshot = page.getByLabel('Snapshot JSON')
  await expect(code).toHaveAttribute('maxlength', '32')
  await expect(snapshot).toHaveAttribute('maxlength', '65536')
  await expect(snapshot).toHaveCSS('font-size', '16px')
  await expect(snapshot).toHaveCSS('line-height', '24px')
  await expect.poll(() => snapshot.evaluate((node) => getComputedStyle(node).fontFamily)).toContain('system-ui')
  await loadBoard(page, 'np1-6-1')
  await expect(page.getByLabel('Grid size')).toHaveValue('6')
  await expect(page.getByLabel('Board code')).toHaveValue('np1-6-1')
  await expect(page.getByRole('button', { name: 'Load board' })).toBeFocused()
})
