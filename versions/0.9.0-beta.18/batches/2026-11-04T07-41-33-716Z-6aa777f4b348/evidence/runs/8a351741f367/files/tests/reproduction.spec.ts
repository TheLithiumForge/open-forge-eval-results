import { expect, test } from '@playwright/test';
import { card, completedText, exported, frozenClock, loadBoard, loadSnapshot, SAMPLE } from './gameActions.ts';

test('native reproduction controls preserve drafts and focus, and validate atomically', async ({ page }) => {
  await frozenClock(page);
  await page.goto('/');
  await expect(page.locator('details')).not.toHaveAttribute('open');
  await loadBoard(page, '  np1-4-1  ');
  await expect(page.getByLabel('Board code', { exact: true })).toHaveValue('np1-4-1');
  await expect(page.getByLabel('Board code', { exact: true })).toHaveAttribute('maxlength', '32');
  await expect(page.getByLabel('Snapshot JSON', { exact: true })).toHaveAttribute('maxlength', '65536');
  await expect(page.getByRole('button', { name: 'Load board', exact: true })).toBeFocused();
  await page.getByLabel('Board code', { exact: true }).fill('draft');
  await card(page, 2).click();
  await expect(page.getByLabel('Board code', { exact: true })).toHaveValue('draft');
  await page.getByRole('button', { name: 'Load board', exact: true }).click();
  await expect(page.locator('.reproduction__status')).toHaveText('Invalid board code.');
  await expect(page.getByLabel('Board code', { exact: true })).toHaveValue('draft');
  await expect(card(page, 2)).toHaveAccessibleName(/cyan solid circle, marker top, revealed/);
  await loadSnapshot(page, '{"version":2}');
  await expect(page.locator('.reproduction__status')).toHaveText('Invalid snapshot.');
  await expect(page.getByLabel('Snapshot JSON', { exact: true })).toHaveValue('{"version":2}');
  await expect(page.getByRole('button', { name: 'Load snapshot', exact: true })).toBeFocused();
  expect((await exported(page)).selection).toEqual({ kind: 'one', index: 2 });
  await expect(page.getByRole('button', { name: 'Export snapshot', exact: true })).toBeFocused();
  await loadBoard(page, 'np1-6-1');
  await expect(page.getByLabel('Grid size', { exact: true })).toHaveValue('6');
  await expect(card(page, 0)).toHaveAttribute('tabindex', '0');
  await page.getByRole('button', { name: 'New Game', exact: true }).click();
  await expect(page.getByRole('button', { name: 'New Game', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Restart', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Restart', exact: true })).toBeFocused();
});

test('unfinished snapshot pauses both clocks and Resume restores remembered focus', async ({ page }) => {
  await frozenClock(page);
  await page.goto('/');
  await loadSnapshot(page, JSON.stringify(SAMPLE));
  await expect(page.locator('.reproduction__status')).toHaveText('Loaded snapshot. Select Resume to continue.');
  await expect(page.locator('.card--revealed')).toHaveCount(4);
  await card(page, 7).click();
  await page.keyboard.press('ArrowRight');
  await expect(card(page, 7)).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(card(page, 11)).toBeFocused();
  await page.keyboard.press('Enter');
  await page.clock.runFor(5000);
  const paused = await exported(page);
  expect(paused.elapsedMs).toBe(1500);
  expect(paused.selection).toEqual(SAMPLE.selection);
  expect(paused.moves).toBe(2);
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await expect(card(page, 11)).toBeFocused();
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toHaveCount(0);
  await page.clock.runFor(299);
  expect((await exported(page)).selection).toEqual({ ...SAMPLE.selection, remainingMs: 1 });
  await page.clock.runFor(1);
  expect((await exported(page)).selection.kind).toBe('closed');
  await expect(page.locator('.card--revealed')).toHaveCount(2);
});

test('export/import round trip preserves progress and completed imports stay static', async ({ page }) => {
  await frozenClock(page);
  await page.goto('/');
  await loadBoard(page);
  await card(page, 2).click();
  await page.clock.runFor(1234);
  const original = await exported(page);
  const text = await page.getByLabel('Snapshot JSON', { exact: true }).inputValue();
  await page.getByRole('button', { name: 'New Game', exact: true }).click();
  await loadSnapshot(page, text);
  expect(await exported(page)).toEqual(original);
  await card(page, 6).click();
  await page.clock.runFor(1000);
  expect(await exported(page)).toEqual(original);
  await loadSnapshot(page, completedText());
  await expect(page.locator('.reproduction__status')).toHaveText('Loaded completed snapshot.');
  await expect(page.locator('.win-banner')).toBeVisible();
  await expect(page.locator('.win-banner')).toHaveCSS('animation-name', 'none');
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toHaveCount(0);
  await expect(page.locator('.game-status')).toContainText('Best: none');
  await page.clock.runFor(5000);
  expect((await exported(page)).elapsedMs).toBe(65000);
});
